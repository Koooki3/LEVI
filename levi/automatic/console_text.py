def language(environ=None) -> str:
    """``zh`` (default) or ``en`` from ``LEVI_AERI_CONSOLE_LANG``."""
    value = str((environ or {}).get(ENV_LANG, "zh")).lower()
    return "en" if value.startswith("en") else "zh"


class Texts:
    """``texts("key", name=value)``: the sentence in the chosen language."""

    def __init__(self, lang="zh"):
        self.lang = lang if lang in TEXT else "zh"

    def __call__(self, key: str, **fields) -> str:
        text = TEXT[self.lang].get(key)
        if text is None:  # never raise on the way to the screen
            text = TEXT["zh"].get(key, key)
        try:
            return text.format(**fields)
        except (KeyError, IndexError, ValueError):
            return text
